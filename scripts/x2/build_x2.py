#!/usr/bin/env python3
"""Generate AgiBot X2 (fixed base, dual omnipicker) configs for Genie Sim.

Source model: AgibotTech/agibot_x2_urdf (Mulan PSL v2), X2_URDF-v1.4.0/X2-Ultra_omnipicker.urdf.
Run scripts/x2/fetch_x2_assets.sh first. Output is committed; re-run to regenerate.
"""
import json, os, re, sys
import numpy as np, trimesh, yaml
import xml.etree.ElementTree as ET

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
CFG = os.path.join(ROOT, "source/data_collection/config")
X2DIR = os.path.join(CFG, "robot_cfg/X2")
SRC = os.path.join(X2DIR, "X2-Ultra_omnipicker.urdf")
OUT_URDF = "X2_omnipicker_fixed_dual.urdf"
CENTER_OFFSET = 0.13  # m along omnipicker base +z (approximation, see docs/X2.md)

ARM = {s: [f"{s}_shoulder_pitch_joint", f"{s}_shoulder_roll_joint", f"{s}_shoulder_yaw_joint",
           f"{s}_elbow_joint", f"{s}_wrist_yaw_joint", f"{s}_wrist_pitch_joint", f"{s}_wrist_roll_joint"]
       for s in ("left", "right")}
CLAW = {"left": "left_claw_joint", "right": "right_claw_joint"}
MIMIC = {"left": "L_hand_wide1_joint", "right": "R_hand_wide1_joint"}
LEGS = [f"{s}_{j}" for s in ("left", "right") for j in
        ("hip_pitch_joint", "hip_roll_joint", "hip_yaw_joint", "knee_joint", "ankle_pitch_joint", "ankle_roll_joint")]
WAIST = ["waist_yaw_joint", "waist_pitch_joint", "waist_roll_joint"]
HEAD = ["head_yaw_joint", "head_pitch_joint"]
# Arms slightly forward/bent: a reachable manipulation home pose inside the URDF limits
HOME = {"left": [0.0, 0.2, 0.0, -1.2, 0.0, 0.0, 0.0], "right": [0.0, -0.2, 0.0, -1.2, 0.0, 0.0, 0.0]}


def build_urdf():
    tree = ET.parse(SRC); r = tree.getroot()
    for s, p in (("l", "L"), ("r", "R")):
        link = ET.SubElement(r, "link", name=f"gripper_{s}_center_link")
        j = ET.SubElement(r, "joint", name=f"gripper_{s}_center_joint", type="fixed")
        ET.SubElement(j, "origin", xyz=f"0 0 {CENTER_OFFSET}", rpy="0 0 0")
        ET.SubElement(j, "parent", link=f"{p}_omnipicker_base_link")
        ET.SubElement(j, "child", link=f"gripper_{s}_center_link")
    tree.write(os.path.join(X2DIR, OUT_URDF), encoding="utf-8", xml_declaration=True)
    return r


def joints(r):
    out = {}
    for j in r.iter("joint"):
        lim = j.find("limit")
        out[j.get("name")] = dict(type=j.get("type"), parent=j.find("parent").get("link"),
                                  child=j.find("child").get("link"),
                                  lower=float(lim.get("lower")) if lim is not None else None,
                                  upper=float(lim.get("upper")) if lim is not None else None)
    return out


def spheres_for(r, link, n=2):
    """Approximate collision spheres from the link's collision mesh bounding box."""
    el = r.find(f"./link[@name='{link}']")
    if el is None or el.find("collision") is None:
        return []
    m = el.find("collision/geometry/mesh")
    if m is None:
        return []
    mesh = trimesh.load(os.path.join(X2DIR, m.get("filename")), force="mesh")
    o = el.find("collision/origin")
    if o is not None:
        T = trimesh.transformations.euler_matrix(*map(float, o.get("rpy", "0 0 0").split()), "sxyz")
        T[:3, 3] = list(map(float, o.get("xyz", "0 0 0").split())); mesh.apply_transform(T)
    lo, hi = mesh.bounds; ext = hi - lo; ax = int(np.argmax(ext))
    rad = float(max(np.sort(ext)[1] / 2, 0.01))
    k = max(1, min(n, int(np.ceil(ext[ax] / (2 * rad)))))
    res = []
    for i in range(k):
        c = (lo + hi) / 2; c[ax] = lo[ax] + ext[ax] * (i + 0.5) / k
        res.append({"center": [round(float(x), 4) for x in c], "radius": round(rad, 4)})
    return res


def main():
    r = build_urdf(); J = joints(r)
    for s in ARM:
        for i, n in enumerate(ARM[s]):
            lo, hi = J[n]["lower"], J[n]["upper"]
            HOME[s][i] = float(np.clip(HOME[s][i], lo, hi))
    rev = [n for n, d in J.items() if d["type"] == "revolute"]
    locked = LEGS + WAIST + HEAD
    # Lula robot descriptions
    for s in ("left", "right"):
        other = "right" if s == "left" else "left"
        d = {"api_version": 1.0, "cspace": ARM[s], "default_q": HOME[s],
             "acceleration_limits": [10] * 7, "jerk_limits": [10000] * 7,
             "cspace_to_urdf_rules": [{"name": n, "rule": "fixed", "value": 0.0} for n in locked]
             + [{"name": n, "rule": "fixed", "value": v} for n, v in zip(ARM[other], HOME[other])]}
        with open(os.path.join(X2DIR, f"X2_omnipicker_fixed_{s}.yaml"), "w") as f:
            f.write("# Generated by scripts/x2/build_x2.py\n"); yaml.safe_dump(d, f, sort_keys=False)
    # cuRobo configs
    arm_links = [J[n]["child"] for s in ARM for n in ARM[s]]
    body_links = ["pelvis", "waist_yaw_link", "waist_pitch_link", "torso_link", "head_yaw_link", "head_pitch_link"]
    hand_links = [J[n]["child"] for n in ("L_omnipicker_joint", "R_omnipicker_joint", "left_claw_joint",
                                         "right_claw_joint", "L_hand_wide1_joint", "R_hand_wide1_joint")]
    coll = [l for l in body_links + arm_links + hand_links if r.find(f"./link[@name='{l}']") is not None]
    sph = {l: s for l in coll if (s := spheres_for(r, l, 3 if l in body_links else 2))}
    coll = [l for l in coll if l in sph]
    lock = {n: 0.0 for n in locked}
    lock.update({CLAW["left"]: 0.0, CLAW["right"]: 0.0})
    for name, ee, cspace, extra_lock in (
            ("X2_omnipicker_fixed_dual.yml", "gripper_l_center_link", ARM["left"] + ARM["right"], {}),
            ("X2_omnipicker_fixed_left.yml", "gripper_l_center_link", ARM["left"],
             dict(zip(ARM["right"], HOME["right"]))),
            ("X2_omnipicker_fixed_right.yml", "gripper_r_center_link", ARM["right"],
             dict(zip(ARM["left"], HOME["left"])))):
        lj = dict(lock); lj.update(extra_lock)
        cfg = {"robot_cfg": {"kinematics": {
            "use_usd_kinematics": False,
            "urdf_path": f"robot/X2/{OUT_URDF}", "asset_root_path": "robot/X2",
            "isaac_usd_path": "robot/X2/fix_robot.usda", "usd_robot_root": "/X2", "usd_path": "robot/X2/robot.usda",
            "base_link": "pelvis", "ee_link": ee,
            "link_names": ["gripper_r_center_link", "gripper_l_center_link"],
            "collision_link_names": coll + ["attached_object", "left_attached_object"],
            "collision_spheres": sph, "collision_sphere_buffer": 0.005,
            "extra_collision_spheres": {"attached_object": 100, "left_attached_object": 100},
            "self_collision_ignore": self_ignore(J, coll),
            "self_collision_buffer": {l: 0.0 for l in coll},
            "lock_joints": lj, "mesh_link_names": coll,
            "cspace": {"joint_names": cspace, "retract_config": sum([HOME[s] for s in ARM if ARM[s][0] in cspace], []),
                       "null_space_weight": [1] * len(cspace), "cspace_distance_weight": [1] * len(cspace),
                       "max_acceleration": 15.0, "max_jerk": 500.0}}}}
        with open(os.path.join(CFG, "curobo/configs/robot", name), "w") as f:
            f.write("# Generated by scripts/x2/build_x2.py -- spheres are bbox approximations\n")
            yaml.safe_dump(cfg, f, sort_keys=False)
    # Genie Sim robot cfg
    order = rev
    init = [0.0 if n in locked else (dict(zip(ARM["left"] + ARM["right"], HOME["left"] + HOME["right"])).get(n)) for n in order]
    rc = {"robot": {
        "robot_name": "X2_omnipicker_fixed", "base_prim_path": "/X2", "arm_base_prim_path": "/X2/torso_link",
        "arm": "dual", "urdf_name": f"/X2/{OUT_URDF}",
        "robot_description": {"right": "/X2/X2_omnipicker_fixed_right.yaml", "left": "/X2/X2_omnipicker_fixed_left.yaml"},
        "robot_usd": "robot/X2/robot_fix.usda", "initial_position": [], "dof_nums": 7, "joint_delta_time": 0.01,
        "lock_joints": locked + [MIMIC["left"], MIMIC["right"]],
        "active_arm_joints": ARM, "init_joint_position": init},
        "camera": {"/X2/head_pitch_link/head_front_Camera": [640, 400]},
        "gripper": {"gripper_type": "angular",
                    "gripper_name": {"left": "gripper_omnipicker", "right": "gripper_omnipicker"},
                    "max_force": 10,
                    "finger_names": {s: [CLAW[s], MIMIC[s]] for s in ARM},
                    "end_effector_name": {"left": "gripper_l_center_link", "right": "gripper_r_center_link"},
                    "end_effector_prim_path": {"left": "/X2/left_wrist_roll_link", "right": "/X2/right_wrist_roll_link"},
                    "end_effector_center_prim_path": {"left": "/X2/gripper_l_center_link", "right": "/X2/gripper_r_center_link"},
                    "gripper_controll_joint": {s: f"/X2/joints/{CLAW[s]}" for s in ARM},
                    # left_claw_joint range is [-1, 0]: open = -1.0 (verify direction in Isaac Sim)
                    "opened_positions": {s: [-1.0, 1.0] for s in ARM},
                    "closed_velocities": {s: [5, -5] for s in ARM}},
        "closed_positions": {s: [0, 0] for s in ARM},
        "curobo": {"curobo_config_file": {"right": "X2_omnipicker_fixed_dual.yml", "left": "X2_omnipicker_fixed_left.yml"},
                   "curobo_urdf_path": "X2", "curobo_urdf_name": f"X2/{OUT_URDF}"}}
    with open(os.path.join(CFG, "robot_cfg/X2_omnipicker_fixed_dual.json"), "w") as f:
        json.dump(rc, f, indent=4)
    with open(os.path.join(X2DIR, "joint_index.json"), "w") as f:
        json.dump(dict(zip(order, init)), f, indent=4)
    p = os.path.join(CFG, "robot_cfg/robot_joint_names.json"); names = json.load(open(p))
    names["X2"] = {"joint_state_order": ARM["left"] + ARM["right"] + HEAD + WAIST,
                   "arm_joint_names": ARM["left"] + ARM["right"],
                   "left_effector_joint_name": [CLAW["left"]], "right_effector_joint_name": [CLAW["right"]],
                   "waist_joint_names": WAIST, "head_joint_names": HEAD, "dof_order": order}
    json.dump(names, open(p, "w"), indent=4)
    print("ok:", len(coll), "collision links,", sum(len(v) for v in sph.values()), "spheres")


def self_ignore(J, links):
    adj = {l: set() for l in links}
    for d in J.values():
        if d["parent"] in adj and d["child"] in adj:
            adj[d["parent"]].add(d["child"]); adj[d["child"]].add(d["parent"])
    return {l: sorted(v) for l, v in adj.items() if v}


if __name__ == "__main__":
    sys.exit(main())
